package com.hootywhooo86.bitweather.pixel

/** Hand-drawn pixel glyphs for UI symbols ('#' = lit). Shared by the app (Compose) and the widgets (Canvas). */
object PixelGlyphs {
    class Glyph(val w: Int, val h: Int, val on: BooleanArray)

    private fun g(vararg rows: String): Glyph {
        val w = rows.maxOf { it.length }
        val on = BooleanArray(w * rows.size)
        rows.forEachIndexed { y, r -> r.forEachIndexed { x, ch -> if (ch == '#') on[y * w + x] = true } }
        return Glyph(w, rows.size, on)
    }

    val all: Map<String, Glyph> = mapOf(
        "degree" to g("###", "#.#", "###"),
        "menu" to g("#######", ".......", "#######", ".......", "#######"),
        "refresh" to g("..###.#", ".#...##", "#...###", "#......", "#.....#", ".#...#.", "..###.."),
        "edit" to g(".....##", "....#.#", "...#.#.", "..#.#..", ".#.#...", "##.....", "##....."),
        "settings" to g("..#.#..", "#######", ".##.##.", "##...##", ".##.##.", "#######", "..#.#.."),
        "back" to g("...#...", "..##...", ".######", "#######", ".######", "..##...", "...#..."),
        "left" to g("...#", "..##", ".###", "####", ".###", "..##", "...#"),
        "right" to g("#...", "##..", "###.", "####", "###.", "##..", "#..."),
        "up" to g("...#...", "..###..", ".#####.", "#######"),
        "down" to g("#######", ".#####.", "..###..", "...#..."),
        "close" to g("##...##", "###.###", ".#####.", "..###..", ".#####.", "###.###", "##...##"),
        "play" to g("#....", "##...", "###..", "####.", "###..", "##...", "#...."),
        "pause" to g("##.##", "##.##", "##.##", "##.##", "##.##", "##.##", "##.##"),
        "plus" to g("..#..", "..#..", "#####", "..#..", "..#.."),
        "check" to g("......#", ".....##", "#...##.", "##.##..", ".###...", "..#...."),
        "pin" to g(".###.", "#####", "##.##", "#####", ".###.", "..#.."),
        "alerts" to g("##", "##", "##", "##", "..", "##"),
        "brief" to g("######", "#....#", "#.##.#", "#....#", "#.##.#", "#....#", "######"),
        "insight" to g("...####", ".....##", "....#.#", "...#..#", "#.#....", "##.....", "#......"),
        "insightDown" to g("#......", "##.....", "#.#....", "...#..#", "....#.#", ".....##", "...####"),
        "hourly" to g("..###..", ".#...#.", "#..#..#", "#..##.#", "#.....#", ".#...#.", "..###.."),
        "daily" to g(".#...#.", "#######", "#######", "#.....#", "#.#.#.#", "#.....#", "#######"),
        "precip" to g("#...#..", "#...#..", "..#...#", "..#...#", "#...#..", "#...#.."),
        "wind" to g("#####..", ".....#.", "#####..", ".......", "######.", "......#", "######."),
        "sun" to g("#..#..#", ".#####.", ".#####.", "#######", ".#####.", ".#####.", "#..#..#"),
        "uv" to g("#..#..#", ".#####.", ".#####.", "#######", ".#####.", ".#####.", "#..#..#"),
        "aqi" to g("##.##..", "..#..##", ".......", "##.##..", "..#..##"),
        "visibility" to g("..###..", ".#...#.", "#..#..#", ".#...#.", "..###.."),
        "humidity" to g("..#..", "..#..", ".###.", "#####", "#####", "#####", ".###."),
        "pressure" to g("..###..", ".#...#.", "#..#..#", "#.#...#", "#.....#", "#######"),
        "feels" to g("..#..", ".#.#.", ".#.#.", ".###.", "#####", "#####", ".###."),
        "moon" to g("..###.", ".##...", "##....", "##....", "##....", ".##...", "..###."),
        "radar" to g("..###..", ".#...#.", "#..#..#", "#.###.#", "#..#..#", ".#...#.", "..###.."),
        "snow" to g("#..#..#", ".#.#.#.", "..###..", "#######", "..###..", ".#.#.#.", "#..#..#"),
        "battery" to g(".##.", "####", "#..#", "####", "####", "####"),
        "bell" to g("..#..", ".###.", ".###.", ".###.", "#####", ".....", "..#.."),
    )

    /** Maps the old text symbols to glyph names. */
    val forSymbol = mapOf(
        "☰" to "menu", "⟳" to "refresh", "✎" to "edit", "⚙" to "settings", "←" to "back", "◀" to "left",
        "▶" to "right", "▲" to "up", "▼" to "down", "✕" to "close", "❚❚" to "pause", "!" to "alerts",
        "*" to "snow", "↗" to "insight", "↘" to "insightDown", "☀" to "sun", "⋮" to "precip", "✓" to "check",
        "☼" to "sun", "☾" to "moon", "◎" to "pin",
    )

    fun of(name: String): Glyph? = all[name] ?: forSymbol[name]?.let { all[it] }
}
